def tbl(data, widths, header=True, aligns=None, small=False):
    rows = []
    for ri, row in enumerate(data):
        out = []
        for cell in row:
            if isinstance(cell, Paragraph):
                out.append(cell)
            else:
                out.append(P(str(cell), styles['TableHead' if header and ri == 0 else ('SmallCN' if small else 'TableCN')]))
        rows.append(out)
    t = Table(rows, colWidths=widths, repeatRows=1 if header else 0, hAlign='LEFT')
    commands = [
        ('GRID', (0, 0), (-1, -1), 0.45, LINE),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('LEFTPADDING', (0, 0), (-1, -1), 5),
        ('RIGHTPADDING', (0, 0), (-1, -1), 5),
        ('TOPPADDING', (0, 0), (-1, -1), 3.5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 3.5),
    ]
    if header:
        commands += [('BACKGROUND', (0, 0), (-1, 0), NAVY), ('TEXTCOLOR', (0, 0), (-1, 0), colors.white)]
        if len(data) > 1:
            commands += [('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, LIGHT])]
    else:
        commands += [('ROWBACKGROUNDS', (0, 0), (-1, -1), [colors.white, LIGHT])]
    if aligns:
        for idx, align in enumerate(aligns):
            commands.append(('ALIGN', (idx, 0), (idx, -1), align))
    t.setStyle(TableStyle(commands))
    return t


class NumberedCanvas(Canvas):
    def __init__(self, *args, **kwargs):
        Canvas.__init__(self, *args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        page_count = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_number(page_count)
            Canvas.showPage(self)
        Canvas.save(self)

    def draw_page_number(self, page_count):
        page = self._pageNumber
        if page == 1:
            return
        w, h = A4
        self.saveState()
        self.setStrokeColor(LINE)
        self.setLineWidth(0.4)
        self.line(18 * mm, 15 * mm, w - 18 * mm, 15 * mm)
        self.setFont('CN', 7.5)
        self.setFillColor(MUTED)
        self.drawString(18 * mm, 10 * mm, '基于AI动态营养算法的个性化饮食推荐与健康管理系统 | 企业命题组修订版')
        self.drawRightString(w - 18 * mm, 10 * mm, f'{page} / {page_count}')
        self.restoreState()


